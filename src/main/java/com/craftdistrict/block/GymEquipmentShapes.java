    private static VoxelShape[][] oldCableMachine() {
        double[][] tower = {
                box(1, 0, 3, 7.25, 1.25, 14.4), box(1.35, 1.25, 5.05, 3, 29.75, 6.65),
                box(1.35, 1.25, 12.25, 3, 29.75, 13.85), box(5.55, 1.25, 4, 7, 29.75, 5.6),
                box(2.85, 1.25, 7.25, 6.15, 12.55, 12.1), box(1.1, 28.95, 3.65, 7.3, 30.85, 14),
                box(6.9, 17.45, 2.95, 9.6, 21.45, 5.2)
        };
        double[][] boxes = new double[tower.length * 2 + 2][];
        for (int i = 0; i < tower.length; i++) {
            double[] b = tower[i];
            boxes[i] = b;
            boxes[tower.length + i] = box(32 - b[3], b[1], b[2], 32 - b[0], b[4], b[5]);
        }
        boxes[boxes.length - 2] = box(7.3, 28.95, 4, 24.7, 30.85, 6.45);
        boxes[boxes.length - 1] = box(10, 27.5, 2.95, 22, 28.55, 4.4);
        return cells(2, 2, 1, boxes);
    }

    private static double[] box(double x, double y, double z, double X, double Y, double Z) {
        return new double[]{x, y, z, X, Y, Z};
    }

    private static VoxelShape[][] cells(int width, int height, int depth, double[]... boxes) {
        VoxelShape[][] result = new VoxelShape[width * height * depth][];
        for (int part = 0; part < result.length; part++) {
            int x = part % width * 16, y = part / (width * depth) * 16, z = part / width % depth * 16;
            VoxelShape shape = Shapes.empty();
            for (double[] b : boxes) {
                double minX = Math.max(0, b[0] - x), minY = Math.max(0, b[1] - y), minZ = Math.max(0, b[2] - z);
                double maxX = Math.min(16, b[3] - x), maxY = Math.min(16, b[4] - y), maxZ = Math.min(16, b[5] - z);
                if (minX < maxX && minY < maxY && minZ < maxZ)
                    shape = Shapes.joinUnoptimized(shape, Block.box(minX, minY, minZ, maxX, maxY, maxZ), BooleanOp.OR);
            }
            result[part] = RestaurantKitchenBlock.rotations(shape);
        }
        return result;
    }
