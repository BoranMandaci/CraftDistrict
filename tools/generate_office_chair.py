"""One reusable static office chair; named geometry also drives cached shapes."""

import copy
import sys

sys.dont_write_bytecode=True
from PIL import Image
from generate_police_entrance import ASSETS, ROOT, MATERIALS as PALETTE, box
from generate_flour_sacks import bounds, omit_hidden_faces, validate_model_elements
from generate_bakery_display_counter import write_json

ID='office_chair'
MATERIALS={name:PALETTE[name] for name in ('dark','metal','light')}
MATERIALS['fabric']='craftdistrict:block/police/office_chair_fabric'
MATERIALS['particle']=MATERIALS['fabric']


def geometry():
    e=[]
    def add(name,a,b,mat):
        p=box(name,a,b,mat); e.append(p); return p
    add('base_left_right',[1.5,1,7.125],[14.5,2,8.875],'metal')
    add('base_front_back',[7.125,1,1.5],[8.875,2,14.5],'metal')
    for name,a,b in (
        ('left',[1.5,0,7.125],[3,1.25,8.875]),
        ('right',[13,0,7.125],[14.5,1.25,8.875]),
        ('front',[7.125,0,1.5],[8.875,1.25,3]),
        ('rear',[7.125,0,13],[8.875,1.25,14.5])):
        add(name+'_caster',a,b,'dark')
    add('central_support_stem',[7.125,2,7.125],[8.875,7.25,8.875],'metal')
    raised_start=len(e)
    add('seat_shell',[3,5.5,3],[13,6.125,12],'dark')
    add('seat_cushion',[3.25,6.125,3.25],[12.75,7,11.75],'fabric')
    add('rear_backrest_mount',[7.125,6.125,11.5],[8.875,9,12.25],'metal')
    frame=add('backrest_shell',[3,7.5,11.125],[13,14.5,12],'dark')
    cushion=add('backrest_cushion',[3.375,8,10.8125],[12.625,14.125,11.125],'fabric')
    for p in (frame,cushion):
        p['rotation']={'origin':[8,7.25,11.5],'axis':'x','angle':22.5,'rescale':False}
    for side,x in (('left',2.5),('right',12.75)):
        add(side+'_arm_support',[x,5.5,8.25],[x+.75,9,9.25],'metal')
        add(side+'_arm_pad',[x-.125,9,4.75],[x+.875,9.625,10],'dark')
    for p in e[raised_start:]:
        for key in ('from','to'): p[key][1]+=1.75
        if 'rotation' in p: p['rotation']['origin'][1]+=1.75
    return e


def block_source(e):
    cells=[]
    for p in e:
        lo,hi=bounds(p)
        cells.append('            Block.box('+', '.join(f'{v:.6f}'.rstrip('0').rstrip('.') for v in lo+hi)+')')
    source='''package com.craftdistrict.block;

//? if >=1.21 {
import com.mojang.serialization.MapCodec;
//?}
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.HorizontalDirectionalBlock;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

/** Generated by tools/generate_office_chair.py; solid-floor placement, no seating. */
public final class OfficeChairBlock extends CashRegisterBlock {
    private static final VoxelShape[] SHAPES = rotations(Shapes.or(
'''+',\n'.join(cells)+''').optimize());
    //? if >=1.21 {
    public static final MapCodec<OfficeChairBlock> CODEC = simpleCodec(OfficeChairBlock::new);
    //?}

    public OfficeChairBlock(Properties properties) {
        super(properties);
    }

    private static VoxelShape[] rotations(VoxelShape north) {
        VoxelShape[] result = new VoxelShape[4];
        result[0] = north;
        for (int turn = 1; turn < 4; turn++) {
            VoxelShape rotated = Shapes.empty();
            for (AABB box : result[turn - 1].toAabbs()) {
                rotated = Shapes.or(rotated, Shapes.box(1 - box.maxZ, box.minY, box.minX,
                        1 - box.minZ, box.maxY, box.maxX));
            }
            result[turn] = rotated.optimize();
        }
        return result;
    }

    @Override
    public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        int turn = switch (state.getValue(BlockStateProperties.HORIZONTAL_FACING)) {
            case EAST -> 1;
            case SOUTH -> 2;
            case WEST -> 3;
            default -> 0;
        };
        return SHAPES[turn];
    }

    //? if >=1.21 {
    @Override
    protected MapCodec<? extends HorizontalDirectionalBlock> codec() {
        return CODEC;
    }
    //?}
}
'''
    (ROOT/'src/main/java/com/craftdistrict/block/OfficeChairBlock.java').write_text(source,encoding='utf-8')


def main():
    fabric=Image.new('RGBA',(16,16))
    for y in range(16):
        for x in range(16):
            shade=-7 if x in (1,14) or y in (1,14) else -2 if (x*3+y*7)%19==0 else 1 if (x+y)%5==0 else 0
            fabric.putpixel((x,y),(60+shade,72+shade,88+shade,255))
    path=ASSETS/'textures/block/police/office_chair_fabric.png'
    path.parent.mkdir(parents=True,exist_ok=True); fabric.save(path)
    e=geometry(); block_source(e)
    for p in e:
        lo,hi=bounds(p)
        assert all(-1e-6<=lo[i]<hi[i]<=16+1e-6 for i in range(3)),p['name']
    omit_hidden_faces(e); validate_model_elements(e)
    model={'parent':'minecraft:block/block','textures':MATERIALS,'elements':e}
    write_json(ASSETS/f'models/block/police/{ID}.json',model)
    write_json(ASSETS/f'blockstates/{ID}.json',{'variants':{
        f'facing={face}':{'model':f'craftdistrict:block/police/{ID}','y':angle}
        for face,angle in (('north',0),('east',90),('south',180),('west',270))}})
    item=copy.deepcopy(model)
    item['display']={
        'gui':{'rotation':[25,135,0],'scale':[.75,.75,.75]},
        'ground':{'translation':[0,3,0],'scale':[.4,.4,.4]},
        'fixed':{'rotation':[0,180,0],'scale':[.7,.7,.7]},
        'thirdperson_righthand':{'rotation':[75,45,0],'scale':[.4,.4,.4]},
        'thirdperson_lefthand':{'rotation':[75,45,0],'scale':[.4,.4,.4]},
        'firstperson_righthand':{'rotation':[0,45,0],'scale':[.6,.6,.6]},
        'firstperson_lefthand':{'rotation':[0,225,0],'scale':[.6,.6,.6]}}
    write_json(ASSETS/f'models/item/{ID}.json',item)
    write_json(ROOT/f'src/main/resources/data/craftdistrict/loot_tables/blocks/{ID}.json',{
        'type':'minecraft:block','pools':[{'rolls':1,'entries':[{'type':'minecraft:item','name':f'craftdistrict:{ID}'}],
        'conditions':[{'condition':'minecraft:survives_explosion'}]}]})
    print(f'{ID}: {len(e)} cuboids; four rotations; one standard static chair.')


if __name__=='__main__': main()
